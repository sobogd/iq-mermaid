// Regenerates content/index.ts from the content tree:
//   content/chrome/<locale>.json   — marketing copy + UI chrome of one locale
//   content/editor/<locale>.json   — strings of the /app workspace
//   content/blog/<id>/<locale>.json — one article in one locale
//
// Run after adding or removing any of them:
//   node scripts/gen-content-index.mjs
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const chromeDir = path.join(root, "content", "chrome");
const editorDir = path.join(root, "content", "editor");
const blogDir = path.join(root, "content", "blog");

const jsonNames = (dir) =>
  fs.existsSync(dir)
    ? fs
        .readdirSync(dir)
        .filter((f) => f.endsWith(".json"))
        .map((f) => f.replace(/\.json$/, ""))
        .sort()
    : [];

const chromeLocales = jsonNames(chromeDir);
const editorLocales = jsonNames(editorDir);

const blogFiles = [];
if (fs.existsSync(blogDir)) {
  for (const id of fs.readdirSync(blogDir).sort()) {
    const dir = path.join(blogDir, id);
    if (!fs.statSync(dir).isDirectory()) continue;
    for (const loc of jsonNames(dir)) blogFiles.push({ id, loc });
  }
}

const ident = (s) => s.replace(/[^a-zA-Z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ""));

let out = `// AUTO-GENERATED by scripts/gen-content-index.mjs — do not edit by hand.
// Static imports (not fs reads, not template-literal dynamic imports) so Next
// bundles every content JSON without output-file-tracing surprises on the
// standalone prod build.
import type { SiteTexts } from "@/app/_landing/types";
import type { BlogArticleContent } from "@/app/_landing/blog/types";
import type { EditorTexts } from "@/app/_editor/texts";
`;
for (const loc of chromeLocales) out += `import chrome_${ident(loc)} from "./chrome/${loc}.json";\n`;
for (const loc of editorLocales) out += `import editor_${ident(loc)} from "./editor/${loc}.json";\n`;
for (const { id, loc } of blogFiles) {
  out += `import blog_${ident(loc)}_${ident(id)} from "./blog/${id}/${loc}.json";\n`;
}

out += `
// Marketing copy + UI chrome, per locale.
export const CHROME: Record<string, SiteTexts> = {
`;
for (const loc of chromeLocales) {
  out += `  ${JSON.stringify(loc)}: chrome_${ident(loc)} as unknown as SiteTexts,\n`;
}
out += `};

// Editor workspace strings, per locale.
export const EDITOR: Record<string, EditorTexts> = {
`;
for (const loc of editorLocales) {
  out += `  ${JSON.stringify(loc)}: editor_${ident(loc)} as unknown as EditorTexts,\n`;
}
out += `};

// Blog articles keyed by \`\${locale}/\${articleId}\`.
export const BLOG_CONTENT: Record<string, BlogArticleContent> = {
`;
for (const { id, loc } of blogFiles) {
  out += `  ${JSON.stringify(`${loc}/${id}`)}: blog_${ident(loc)}_${ident(id)} as unknown as BlogArticleContent,\n`;
}
out += `};

// Locales whose chrome AND editor strings both exist — the rollout gate for
// static params, sitemap, hreflang and the footer's language switcher. A
// locale with only half its files would render a half-English page.
export const READY_LOCALES: string[] = ${JSON.stringify(
  chromeLocales.filter((l) => editorLocales.includes(l)),
)};
`;

fs.writeFileSync(path.join(root, "content", "index.ts"), out);
console.log(
  `content/index.ts: ${chromeLocales.length} chrome, ${editorLocales.length} editor, ${blogFiles.length} blog files`,
);
